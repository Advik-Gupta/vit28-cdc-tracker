import path from "node:path";

/**
 * Postgres access. With DATABASE_URL set (Supabase) it talks to that database;
 * without it, an embedded Postgres in data/pg is used so the app runs with no setup.
 */

export type Q = <T = Record<string, unknown>>(text: string, params?: unknown[]) => Promise<T[]>;
type Conn = { q: Q; tx: <T>(fn: (q: Q) => Promise<T>) => Promise<T> };

// Times are epoch milliseconds in DOUBLE PRECISION, and ids are INTEGER, so both drivers hand back plain numbers.
const TABLES = ["settings", "emails", "companies", "drives", "rounds", "round_emails", "students", "round_students", "roster"];
const SCHEMA = `
CREATE TABLE IF NOT EXISTS settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS emails (
  id TEXT PRIMARY KEY,
  thread_id TEXT,
  subject TEXT NOT NULL DEFAULT '',
  sender TEXT NOT NULL DEFAULT '',
  sent_at DOUBLE PRECISION NOT NULL,
  body_text TEXT NOT NULL DEFAULT '',
  body_html TEXT NOT NULL DEFAULT '',
  attachments JSONB NOT NULL DEFAULT '[]',
  sheet_students JSONB NOT NULL DEFAULT '[]',
  status TEXT NOT NULL DEFAULT 'pending',
  kind TEXT,
  relevant BOOLEAN,
  confidence DOUBLE PRECISION,
  summary TEXT,
  error TEXT,
  drive_id INTEGER,
  student_count INTEGER NOT NULL DEFAULT 0,
  processed_at DOUBLE PRECISION
);
CREATE INDEX IF NOT EXISTS emails_status ON emails(status, sent_at);
CREATE INDEX IF NOT EXISTS emails_drive ON emails(drive_id);

CREATE TABLE IF NOT EXISTS companies (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  key TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS drives (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id INTEGER NOT NULL,
  category TEXT NOT NULL DEFAULT 'other',
  batch TEXT NOT NULL DEFAULT '',
  program TEXT NOT NULL DEFAULT '',
  role TEXT,
  stipend_monthly INTEGER,
  stipend_text TEXT,
  ctc_lpa DOUBLE PRECISION,
  ctc_text TEXT,
  locations TEXT,
  eligible_branches TEXT,
  criteria TEXT,
  deadline TEXT,
  website TEXT,
  first_seen DOUBLE PRECISION NOT NULL,
  last_update DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS drives_company ON drives(company_id);

CREATE TABLE IF NOT EXISTS rounds (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  drive_id INTEGER NOT NULL,
  type TEXT NOT NULL,
  name TEXT NOT NULL,
  date TEXT,
  time TEXT,
  venue TEXT,
  mode TEXT,
  list_email_id TEXT,
  created_at DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS rounds_drive ON rounds(drive_id);

CREATE TABLE IF NOT EXISTS round_emails (
  round_id INTEGER NOT NULL,
  email_id TEXT NOT NULL,
  PRIMARY KEY (round_id, email_id)
);

CREATE TABLE IF NOT EXISTS students (
  regno TEXT PRIMARY KEY,
  name TEXT NOT NULL DEFAULT '',
  branch TEXT NOT NULL,
  year TEXT NOT NULL,
  campus TEXT NOT NULL DEFAULT 'vellore'
);
CREATE INDEX IF NOT EXISTS students_branch ON students(branch);

CREATE TABLE IF NOT EXISTS round_students (
  round_id INTEGER NOT NULL,
  regno TEXT NOT NULL,
  PRIMARY KEY (round_id, regno)
);
CREATE INDEX IF NOT EXISTS round_students_regno ON round_students(regno);

-- The list of Vellore students (from vit_students.xlsx): names for bare register numbers, and branch sizes.
CREATE TABLE IF NOT EXISTS roster (
  regno TEXT PRIMARY KEY,
  name TEXT NOT NULL DEFAULT '',
  branch TEXT NOT NULL
);

-- Supabase exposes every table over its public API. Row level security with no
-- policies closes that door; this app connects directly and is not affected.
${TABLES.map((t) => `ALTER TABLE ${t} ENABLE ROW LEVEL SECURITY;`).join("\n")}
`;

const g = globalThis as unknown as { __cdcPg?: Promise<Conn> };

async function connect(): Promise<Conn> {
  const url = process.env.DATABASE_URL;
  if (url) {
    const { default: postgres } = await import("postgres");
    // prepare: false is required by Supabase's transaction pooler.
    const sql = postgres(url, { prepare: false, max: 3, idle_timeout: 20, onnotice: () => {} });
    await sql.unsafe(SCHEMA);
    const wrap = (s: { unsafe: typeof sql.unsafe }): Q => async (text, params = []) =>
      (await s.unsafe(text, params as never[])) as never;
    return { q: wrap(sql), tx: (fn) => sql.begin((t) => fn(wrap(t as never))) as never };
  }
  const { PGlite } = await import("@electric-sql/pglite");
  const { mkdirSync } = await import("node:fs");
  const dir = path.join(process.env.DATA_DIR ? path.resolve(process.env.DATA_DIR) : path.join(process.cwd(), "data"), "pg");
  mkdirSync(dir, { recursive: true });
  const db = new PGlite(dir);
  await db.exec(SCHEMA);
  const wrap = (s: { query: typeof db.query }): Q => async (text, params = []) =>
    (await s.query(text, params)).rows as never;
  return { q: wrap(db), tx: (fn) => db.transaction((t) => fn(wrap(t as never))) as never };
}

const conn = () => (g.__cdcPg ??= connect());

export const q: Q = async (text, params) => (await conn()).q(text, params);
export const tx = async <T>(fn: (q: Q) => Promise<T>): Promise<T> => (await conn()).tx(fn);
export const usingSupabase = () => Boolean(process.env.DATABASE_URL);

export async function getSetting(key: string): Promise<string | null> {
  const rows = await q<{ value: string }>("SELECT value FROM settings WHERE key = $1", [key]);
  return rows[0]?.value ?? null;
}

export async function setSetting(key: string, value: string | null) {
  if (value === null) await q("DELETE FROM settings WHERE key = $1", [key]);
  else await q("INSERT INTO settings (key, value) VALUES ($1, $2) ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value", [key, value]);
}
